/* Atlas basemap — the single seam every interactive atlas draws its ground from.
 *
 * Why this file exists
 * --------------------
 * Until 2026-08-31 each atlas page carried its own inline MapLibre style
 * pointing at `basemaps.cartocdn.com/dark_all`. CARTO moved that endpoint
 * behind an API key and began serving HTTP 200 PNGs stamped "API KEY REQUIRED"
 * instead of map imagery, so every atlas rendered its evidence on top of a
 * vendor error notice — and, because the tiles were 200s rather than 4xx,
 * nothing in the page could tell that anything had failed.
 *
 * The substrate is now served from this site: Natural Earth 1:50m, public
 * domain, no key, no rate limit, no usage policy to breach, generated by
 * `tools/build_basemap.py` (see `docs/assets/basemap/PROVENANCE.md`).
 *
 * Doctrine, unchanged from the static specimens: the basemap is cartographic
 * SUBSTRATE, not evidence. It is drawn in near-black so that case markers,
 * overlays and utility colours stay the only things a reader can read.
 *
 * Changing the basemap
 * --------------------
 * Everything a provider swap touches is in CONFIG below; no atlas page names a
 * tile URL. To point every atlas at a raster XYZ provider instead, set
 * `rasterTiles` here — or, per page or per deployment, define
 * `window.ATLAS_BASEMAP_CONFIG = { rasterTiles: [...] }` before this script
 * loads. Anything set there is merged over the defaults.
 */
(function (global) {
  'use strict';

  var CONFIG = {
    // Self-hosted vector substrate. Paths resolve against this script's own
    // URL, so a page at any depth under docs/ gets them right.
    landUrl: 'basemap/land.geojson',
    admin1Url: 'basemap/admin1.geojson',
    attribution:
      'Boundaries: <a href="https://www.naturalearthdata.com/">Natural Earth</a> ' +
      '1:50m (public domain)',

    // Ink. Sampled from the basemap this replaced, so the pages keep the value
    // relationships they were composed against: land reads slightly above the
    // sea, both far below any marker.
    seaColor: '#090909',
    landColor: '#262626',
    coastColor: '#3b3b3b',        // country outlines and coastline
    subnationalColor: '#333333',  // US / CA / MX state and province lines

    // Optional override: an XYZ raster provider, e.g.
    //   rasterTiles: ['https://.../{z}/{x}/{y}@2x.png']
    // Null keeps the self-hosted vector substrate. Note that a raster provider
    // is exactly the dependency that broke here: a keyed provider that answers
    // 200 with a watermark cannot be detected as a failure by this page or any
    // other. Prefer fixing the substrate over renting one.
    rasterTiles: null,
    rasterAttribution: '',
    rasterTileSize: 256
  };

  var override = global.ATLAS_BASEMAP_CONFIG;
  if (override) {
    for (var k in override) {
      if (Object.prototype.hasOwnProperty.call(override, k)) CONFIG[k] = override[k];
    }
  }

  // Resolve data paths against this script, not the page.
  var here = (document.currentScript && document.currentScript.src) || '';
  function url(p) {
    return /^(https?:)?\/\//.test(p) ? p : new URL(p, here || location.href).href;
  }

  var SOURCE_IDS = ['atlas-land', 'atlas-admin1', 'atlas-raster'];

  function style() {
    if (CONFIG.rasterTiles) {
      return {
        version: 8,
        sources: {
          'atlas-raster': {
            type: 'raster',
            tiles: CONFIG.rasterTiles,
            tileSize: CONFIG.rasterTileSize,
            attribution: CONFIG.rasterAttribution
          }
        },
        layers: [
          { id: 'atlas-sea', type: 'background',
            paint: { 'background-color': CONFIG.seaColor } },
          { id: 'atlas-raster-layer', type: 'raster', source: 'atlas-raster',
            minzoom: 0, maxzoom: 19 }
        ]
      };
    }

    // maxzoom caps how deep geojson-vt indexes; polygons stay sharp when
    // over-zoomed past it, and the index stays cheap to build.
    var vector = { type: 'geojson', maxzoom: 10, attribution: CONFIG.attribution };

    return {
      version: 8,
      sources: {
        'atlas-land': Object.assign({ data: url(CONFIG.landUrl) }, vector),
        'atlas-admin1': Object.assign({ data: url(CONFIG.admin1Url) }, vector)
      },
      layers: [
        { id: 'atlas-sea', type: 'background',
          paint: { 'background-color': CONFIG.seaColor } },
        { id: 'atlas-land-fill', type: 'fill', source: 'atlas-land',
          paint: { 'fill-color': CONFIG.landColor } },
        { id: 'atlas-admin1-line', type: 'line', source: 'atlas-admin1',
          minzoom: 3,
          paint: {
            'line-color': CONFIG.subnationalColor,
            'line-width': ['interpolate', ['linear'], ['zoom'], 3, 0.4, 8, 0.9],
            'line-opacity': ['interpolate', ['linear'], ['zoom'], 3, 0.5, 5, 1]
          } },
        { id: 'atlas-coast-line', type: 'line', source: 'atlas-land',
          paint: {
            'line-color': CONFIG.coastColor,
            'line-width': ['interpolate', ['linear'], ['zoom'], 1, 0.4, 6, 1.1]
          } }
      ]
    };
  }

  /* Failure handling.
   *
   * A substrate served from this origin fails loudly — a 404, a network error
   * or a parse error raises a MapLibre `error` carrying the source id — unlike
   * the keyed vendor tiles it replaced, which failed silently at HTTP 200 with
   * a watermark drawn into the imagery. Nothing on a page can detect that.
   *
   * Two things have to happen when it does fail. First, drop the broken
   * substrate: MapLibre withholds the map's `load` event until every source in
   * the style has loaded, and each atlas builds its case layers, filters and
   * detail panel inside `map.on('load')`. A source stuck in error would
   * therefore take the whole atlas down with the basemap. Second, say so once,
   * quietly, at the foot of the map.
   *
   * What is left is the background colour, the cases, the overlays and every
   * control. An atlas with no ground under its markers is still an atlas.
   */
  function drop(map, sourceId) {
    try {
      if (!map.getSource(sourceId)) return;
      map.getStyle().layers.forEach(function (l) {
        if (l.source === sourceId && map.getLayer(l.id)) map.removeLayer(l.id);
      });
      map.removeSource(sourceId);
    } catch (e) { /* the map is already in a worse state than we can mend */ }
  }

  function notice(map) {
    if (document.querySelector('.basemap-notice')) return;
    var el = document.createElement('div');
    el.className = 'basemap-notice';
    el.setAttribute('role', 'status');
    el.textContent = 'Basemap unavailable — case data is unaffected.';
    el.style.cssText =
      'position:absolute;left:50%;bottom:14px;transform:translateX(-50%);' +
      'z-index:5;pointer-events:none;background:rgba(17,17,17,.92);' +
      'border:1px solid #2a2a2a;border-radius:3px;color:#8a8a8a;' +
      'font:12px/1.4 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif;' +
      'padding:6px 10px;max-width:80%;text-align:center';
    var host = map.getContainer();
    if (getComputedStyle(host).position === 'static') host.style.position = 'relative';
    host.appendChild(el);
  }

  function watch(map) {
    map.on('error', function (ev) {
      var id = ev && ev.sourceId;
      if (!id || SOURCE_IDS.indexOf(id) === -1) return;
      // Deferred: removing a source from inside its own error event re-enters
      // the style update that raised it.
      setTimeout(function () { drop(map, id); notice(map); }, 0);
    });
    return map;
  }

  global.AtlasBasemap = { style: style, watch: watch, config: CONFIG };
})(window);
